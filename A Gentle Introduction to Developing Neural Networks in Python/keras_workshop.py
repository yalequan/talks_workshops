ax2.plot(reg_history.history['val_loss'], label='Validation Loss', color='orange')
ax2.set_title('Regression: Mean Squared Error (MSE)')
ax2.set_xlabel('Epoch')
ax2.set_ylabel('Loss (MSE)')
ax2.legend()
