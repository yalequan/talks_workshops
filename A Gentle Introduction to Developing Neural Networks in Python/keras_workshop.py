"""### **Final Evaluation**
Let's see how both correctly specified models perform on the 20% of data they have **never seen before**.
"""

# --- Baselines ---
# Before interpreting our results, we establish a "naive" baseline for each task.
# A baseline is the simplest possible model -- if our neural network can't beat
# this, it hasn't learned anything useful.

# Classification baseline: always predict the majority class
majority_class = y_class_train.mode()[0]
baseline_acc = (y_class_test == majority_class).mean()
print(f"Baseline Accuracy (always predict '{majority_class}'): {baseline_acc * 100:.2f}%")

# Regression baseline: always predict the training set mean
