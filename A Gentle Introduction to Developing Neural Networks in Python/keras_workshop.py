print("\n--- CLASSIFICATION RESULTS ---")
class_loss, class_acc = class_model.evaluate(X_test_scaled, y_class_test, verbose=0)
print(f"Model Accuracy:   {class_acc * 100:.2f}%  |  Baseline: {baseline_acc * 100:.2f}%  |  Improvement: +{(class_acc - baseline_acc) * 100:.2f}%")

print("\n--- REGRESSION RESULTS ---")
reg_loss, reg_mae = reg_model.evaluate(X_test_scaled, y_reg_test, verbose=0)
